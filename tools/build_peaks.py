#!/usr/bin/env python3
"""Precompute waveform peak envelopes for every audio clip in the demo.

The demo page is a dependency-free static site, so the waveform must not be
decoded in the browser at runtime. This script decodes each mp3 with ffmpeg and
stores a compact 0-100 envelope in assets/peaks.js.

Usage:  python3 tools/build_peaks.py
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
CASES = ROOT / "cases"
OUT = ROOT / "assets" / "peaks.js"

SR = 16000
BARS = 200
REF_BARS = 220


def probe_duration(path: Path) -> float:
    out = subprocess.run(
        [
            "ffprobe", "-v", "error",
            "-show_entries", "format=duration",
            "-of", "default=nw=1:nk=1",
            str(path),
        ],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    return round(float(out), 3)


def decode(path: Path) -> np.ndarray:
    raw = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", str(path), "-ac", "1", "-ar", str(SR),
         "-f", "f32le", "-"],
        capture_output=True,
        check=True,
    ).stdout
    return np.frombuffer(raw, dtype="<f4")


def envelope(samples: np.ndarray, bars: int) -> list[int]:
    n = samples.size
    if n == 0:
        return [1] * bars
    edges = np.linspace(0, n, bars + 1).astype(np.int64)
    rms = np.empty(bars, dtype=np.float64)
    for i in range(bars):
        seg = samples[edges[i]:edges[i + 1]]
        rms[i] = float(np.sqrt(np.mean(np.square(seg)))) if seg.size else 0.0
    ref = np.percentile(rms, 95)
    if ref <= 1e-9:
        ref = max(float(rms.max()), 1e-9)
    norm = np.clip(rms / ref, 0.0, 1.0) ** 0.75
    # 1..100 keeps every bar visible while leaving room for quiet passages.
    return [int(round(1 + 99 * v)) for v in norm]


def main() -> int:
    clips: dict[str, dict] = {}
    for case_dir in sorted(p for p in CASES.iterdir() if p.is_dir()):
        for mp3 in sorted(case_dir.glob("*.mp3")):
            rel = mp3.relative_to(ROOT).as_posix()
            bars = REF_BARS if mp3.name == "ref.mp3" else BARS
            samples = decode(mp3)
            clips[rel] = {
                "duration": probe_duration(mp3),
                "peaks": envelope(samples, bars),
            }
            print(f"  {rel:48s} {clips[rel]['duration']:7.3f}s", file=sys.stderr)

    header = (
        "/* Auto-generated by tools/build_peaks.py -- do not edit by hand. */\n"
        "window.DEMO_CLIPS = "
    )
    OUT.write_text(
        header + json.dumps(clips, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT} ({OUT.stat().st_size / 1024:.1f} KiB, {len(clips)} clips)",
          file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
