#!/usr/bin/env python3
"""Generate assets/data.js (the page's only data source) from the demo manifest.

The site itself is a static, dependency-free bundle that must also work from
file://, so data is emitted as a plain script (no fetch/XHR).

Usage:
    python3 tools/build_data.py /path/to/demo_7dialects_6models/manifest.json
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "data.js"

# Display names. Keys match the manifest's dialect strings.
DIALECTS = {
    "粤语": {"zh": "粤语", "en": "Yue"},
    "吴语": {"zh": "吴语", "en": "Wu"},
    "四川话": {"zh": "四川话", "en": "Sichuan"},
    "东北话": {"zh": "东北话", "en": "Northeastern"},
    "陕西话": {"zh": "陕西话", "en": "Shaanxi"},
    "河南话": {"zh": "河南话", "en": "Henan"},
    "闽南话": {"zh": "闽南话", "en": "Southern Min"},
}

MODELS = {
    "main": {
        "labelEn": "Ours (DSI-CDTTS)",
        "labelZh": "本文主模型",
        "noteEn": "Full method",
        "noteZh": "完整方法",
        "ours": True,
    },
    "m2d": {
        "labelEn": "M2D only",
        "labelZh": "仅 M2D",
        "noteEn": "Ablation: M2D-only training",
        "noteZh": "消融：仅 M2D 训练",
    },
    "cv3": {
        "labelEn": "D2D w/ cloned refs",
        "labelZh": "D2D + 克隆参考",
        "noteEn": "Ablation: D2D with cloned references",
        "noteZh": "消融：D2D + 克隆参考",
    },
    "cosy": {
        "labelEn": "CosyVoice3",
        "labelZh": "CosyVoice3",
        "noteEn": "External baseline",
        "noteZh": "外部基线",
    },
    "firered": {
        "labelEn": "FireRedTTS3",
        "labelZh": "FireRedTTS3",
        "noteEn": "External baseline",
        "noteZh": "外部基线",
    },
    "vox": {
        "labelEn": "VoxCPM2 base",
        "labelZh": "VoxCPM2 base",
        "noteEn": "Public base model",
        "noteZh": "公开基座模型",
    },
}

MODEL_ORDER = ["main", "m2d", "cv3", "cosy", "firered", "vox"]

# Original ref_region strings are corpus-internal (e.g. "上海上海上海").
REGIONS = {
    "上海上海上海": {"zh": "上海", "en": "Shanghai"},
    "河南信阳市固始县": {"zh": "河南固始", "en": "Gushi, Henan"},
    "广东湛江廉江": {"zh": "广东廉江", "en": "Lianjiang, Guangdong"},
    "四川凉山彝族自治州西昌市": {"zh": "四川西昌", "en": "Xichang, Sichuan"},
    "陕西西安市户县": {"zh": "陕西户县", "en": "Huxian, Shaanxi"},
    "香港": {"zh": "香港", "en": "Hong Kong"},
}


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    manifest_path = Path(sys.argv[1]).expanduser().resolve()
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))

    cases = []
    for i, case in enumerate(manifest["cases"], start=1):
        target = case["target_language"]
        source = case["source_language"]
        region = REGIONS.get(case["ref_region"], {"zh": case["ref_region"], "en": case["ref_region"]})
        case_id = case["ref_audio"].split("/")[1]
        clips = {}
        for key in MODEL_ORDER:
            entry = case["models"][key]
            clips[key] = entry["audio"]
        cases.append(
            {
                "id": case_id,
                "index": i,
                "dialect": target,
                "sourceDialect": source,
                "sample": case["sample"],
                "text": case["text"].strip(),
                "region": region,
                "ref": case["ref_audio"],
                "clips": clips,
            }
        )

    payload = {
        "paper": {
            "name": "DSI-CDTTS",
            "fullEn": "Double Self-Improvement for Cross-Dialect Text-to-Speech",
            "fullZh": "面向跨方言语音克隆的双重自提升框架",
        },
        "dialects": DIALECTS,
        "models": MODELS,
        "modelOrder": MODEL_ORDER,
        "cases": cases,
    }

    body = json.dumps(payload, ensure_ascii=False, indent=2)
    OUT.write_text(
        "/* Auto-generated by tools/build_data.py -- do not edit by hand. */\n"
        "window.DEMO_DATA = " + body + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT} ({OUT.stat().st_size / 1024:.1f} KiB, {len(cases)} cases)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
